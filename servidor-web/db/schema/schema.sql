-- tables
-- Table: Catalogue
CREATE TABLE Catalogue (
    id_user int  NOT NULL,
    id_game int  NOT NULL,
    score int,
    status varchar(20) NOT NULL,
    CONSTRAINT check_score CHECK (score BETWEEN 1 AND 5) NOT DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT Catalogue_pk PRIMARY KEY (id_game,id_user)
);

-- Table: Library
CREATE TABLE Library (
    id_game int  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title varchar(255)  NOT NULL,
    description text  NOT NULL,
    avg_score decimal(3,2) DEFAULT 0,
    CONSTRAINT Library_pk PRIMARY KEY (id_game)
);

-- Table: Users
CREATE TABLE Users (
    id_user int  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
