    password varchar(255)  NOT NULL,
    CONSTRAINT Users_unique_email UNIQUE (email) NOT DEFERRABLE  INITIALLY IMMEDIATE,
    CONSTRAINT Users_pk PRIMARY KEY (id_user)
);

