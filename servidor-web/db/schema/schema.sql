-- Functions
-- Función que recalcula el promedio y actualiza la tabla Library
CREATE OR REPLACE FUNCTION update_game_avg_score()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE Library
    SET avg_score = (
        SELECT COALESCE(AVG(score), 0)::decimal(3,2)
        FROM Catalogue
        WHERE id_game = COALESCE(NEW.id_game, OLD.id_game)
    )
    WHERE id_game = COALESCE(NEW.id_game, OLD.id_game);

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Triggers
-- Trigger asociado a la tabla Catalogue
CREATE TRIGGER trg_update_avg_score
AFTER INSERT OR UPDATE OF score OR DELETE
ON Catalogue
FOR EACH ROW
EXECUTE FUNCTION update_game_avg_score();

